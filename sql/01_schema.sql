CREATE OR REPLACE VIEW public.v_table_roles AS
SELECT n.nspname AS schema_name, c.relname AS table_name,
       substring(d.description FROM 'role=([A-Z-]+)')    AS role,
       substring(d.description FROM 'spatial=(yes|no)')  AS spatial,
       substring(d.description FROM 'temporal=(yes|no)') AS temporal,
       d.description
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN pg_description d ON d.objoid = c.oid AND d.objsubid = 0
WHERE n.nspname IN ('public','sim') AND c.relkind IN ('r','p') AND c.relname <> 'spatial_ref_sys'
ORDER BY role, n.nspname, c.relname;

