-- =====================================================================
-- 02_map_and_data.sql
-- A synthetic campus (roads, zones, stops, routes), vehicles, drivers and a
-- timetable, generated by SQL, with verification queries.
--
-- Run in : pgAdmin 4 > Query Tool on campus_shuttle, AFTER 01_schema.sql.
-- Changes: inserts only. Rerunnable: every insert is skipped when its table
--          already has data.
-- How    : run one PART at a time (A, B, C ...); each ends with a verify query.
--
-- The map is about 2.6 km x 2.0 km: a 6 x 5 grid of road junctions with
-- deterministic jitter and curvature, three links removed so it is not a plain
-- grid, and 12 stops placed on junctions. Everything is labelled 'simulated'.
-- A real campus would replace PARTs A-D with an OpenStreetMap import; nothing
-- else in the project would change.
-- =====================================================================

-- =====================================================================
-- PART A: roads (46 segments)
-- Junction (i,j) has node_id = j*6 + i + 1, i in 0..5 (east), j in 0..4 (north).
-- Each segment is a 5-vertex curve between two junctions; endpoints match
-- the junction coordinates exactly.
-- =====================================================================
WITH nodes AS (
    SELECT j * 6 + i + 1 AS node_id, i, j,
