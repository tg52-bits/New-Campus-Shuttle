-- ================= BEGIN 01_schema.sql =================

-- =====================================================================
-- 01_schema.sql   (Campus Shuttle, schema v3)
-- A lean spatio-temporal schema: 15 core tables + 5 simulator tables.
--
-- Run in : pgAdmin 4 > Query Tool, connected to a NEW EMPTY database named
--          campus_shuttle (PostgreSQL 17 on Windows, PostGIS installed).
-- Nature : creates objects only; inserts no data except the documented
--          tuning parameters in service_params.
-- Rerun  : safe on a v3 database (IF NOT EXISTS). Refuses to run on a
--          database that holds the older v1/v2 schema.
-- Setup  : pgAdmin > right-click Databases > Create > Database... > campus_shuttle
--          (keep any older database under another name as a backup).
--
-- Design in one paragraph
--   Only reference data is typed in (map, stops, routes, timetable, vehicles).
--   The one raw operational stream is vehicle_position (timestamped GPS).
--   Everything else - route lines, planned times, stop arrivals and
--   departures, trip status, segment travel times - is DERIVED by triggers
--   (file 03), so tables are few and nothing is entered twice.
--
-- Table roles (also queryable:  SELECT * FROM v_table_roles;)
--   STATIC-SPATIAL     campus_zones, road_segments, stops, routes
--   STATIC-STRUCTURE   route_stops, route_segments
--   REFERENCE          vehicles, drivers
--   TEMPORAL-REFERENCE timetable_departures, road_closures
--   CONFIG             service_params
--   DYNAMIC-PLAN       trips, trip_stop_event
--   DYNAMIC-RAW        vehicle_position (+ derived columns on the same row)
--   DYNAMIC-DERIVED    segment_traversal
--   GROUND-TRUTH       sim.*  (simulator only; no trigger or rider query reads them,
--                      except sim.clock, which gives the demo its adjustable "now")
-- =====================================================================


-- =====================================================================
-- PART 0: guard, extensions, schema, provenance label
-- =====================================================================
DO $$
BEGIN
    IF to_regclass('public.position_match') IS NOT NULL
       OR to_regclass('public.vehicle_status_history') IS NOT NULL
       OR (to_regclass('public.trips') IS NOT NULL AND NOT EXISTS (
              SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public' AND table_name = 'trips' AND column_name = 'service_date')) THEN
        RAISE EXCEPTION 'An older (v1/v2) schema was detected in this database. Create a new empty database and run this script there.';
    END IF;
END $$;

CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS btree_gist;   -- for exclusion constraints on time ranges

CREATE SCHEMA IF NOT EXISTS sim;             -- simulator bookkeeping and ground truth

-- Provenance label for tables that can mix real and synthetic rows.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
                   WHERE n.nspname = 'public' AND t.typname = 'data_source_t') THEN
        CREATE DOMAIN public.data_source_t AS text
            NOT NULL DEFAULT 'unspecified'
            CHECK (VALUE IN ('unspecified','real_observed','real_osm','real_published',
                             'derived','simulated','assumed'));
    END IF;
END $$;


-- =====================================================================
-- PART 1: STATIC spatial layer (the fixed map)
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.campus_zones (
    zone_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_name    varchar(100) NOT NULL UNIQUE,
    zone_type    varchar(30)  NOT NULL DEFAULT 'other'
                 CHECK (zone_type IN ('academic','residential','sports','gate','service','forest','other')),
    boundary     geometry(MultiPolygon, 4326) NOT NULL,
    data_source  public.data_source_t,
    CONSTRAINT chk_campus_zones_boundary_valid CHECK (ST_IsValid(boundary) AND NOT ST_IsEmpty(boundary))
);

CREATE TABLE IF NOT EXISTS public.road_segments (
    road_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    osm_way_id       bigint,
    road_name        varchar(150),
    highway_class    varchar(50),
    oneway           boolean NOT NULL DEFAULT false,
    speed_limit_kmh  numeric(5,1) CHECK (speed_limit_kmh IS NULL OR speed_limit_kmh > 0),
    geom             geometry(LineString, 4326) NOT NULL,
    length_m         numeric(10,2) GENERATED ALWAYS AS (ST_Length(geom::geography)) STORED,
    source_node      integer,
    target_node      integer,
    data_source      public.data_source_t DEFAULT 'real_osm',
    CONSTRAINT chk_road_segments_geom_valid
        CHECK (ST_IsValid(geom) AND NOT ST_IsEmpty(geom) AND ST_NPoints(geom) >= 2)
);

-- Junctions of the road network, derived from segment endpoints.
CREATE OR REPLACE VIEW public.v_road_nodes AS
SELECT DISTINCT ON (node_id) node_id, geom
FROM (SELECT source_node AS node_id, ST_StartPoint(geom) AS geom FROM public.road_segments WHERE source_node IS NOT NULL
      UNION ALL
      SELECT target_node, ST_EndPoint(geom) FROM public.road_segments WHERE target_node IS NOT NULL) q
ORDER BY node_id;

CREATE TABLE IF NOT EXISTS public.stops (
    stop_id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_code         varchar(20) UNIQUE,
    stop_name         varchar(100) NOT NULL UNIQUE,
    location          geometry(Point, 4326) NOT NULL,                       -- INPUT
    zone_id           integer REFERENCES public.campus_zones(zone_id),      -- derived
    road_id           integer REFERENCES public.road_segments(road_id),     -- derived
    snapped_location  geometry(Point, 4326),                                -- derived
    snap_distance_m   numeric(8,2) CHECK (snap_distance_m IS NULL OR snap_distance_m >= 0),  -- derived
    data_source       public.data_source_t,
    CONSTRAINT chk_stops_location_valid
        CHECK (ST_IsValid(location) AND NOT ST_IsEmpty(location)
               AND ST_X(location) BETWEEN -180 AND 180 AND ST_Y(location) BETWEEN -90 AND 90)
);

CREATE TABLE IF NOT EXISTS public.routes (
    route_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_code      varchar(20)  NOT NULL UNIQUE,
    route_name      varchar(150) NOT NULL UNIQUE,
    route_geometry  geometry(LineString, 4326),                             -- derived
    length_m        numeric(10,2) GENERATED ALWAYS AS (
                        CASE WHEN route_geometry IS NULL THEN NULL
                             ELSE ST_Length(route_geometry::geography) END) STORED,
    data_source     public.data_source_t,
    CONSTRAINT chk_routes_geometry_valid
        CHECK (route_geometry IS NULL
               OR (ST_IsValid(route_geometry) AND NOT ST_IsEmpty(route_geometry) AND ST_NPoints(route_geometry) >= 2))
);

-- Ordered stops of a route. A stop may repeat (loops), so only the sequence is unique.
CREATE TABLE IF NOT EXISTS public.route_stops (
    route_stop_id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id                    integer NOT NULL REFERENCES public.routes(route_id) ON DELETE CASCADE,
    stop_id                     integer NOT NULL REFERENCES public.stops(stop_id),
    stop_sequence               integer NOT NULL CHECK (stop_sequence > 0),
    distance_from_start_m       numeric(10,2) CHECK (distance_from_start_m IS NULL OR distance_from_start_m >= 0), -- derived
    planned_arrival_offset_s    integer CHECK (planned_arrival_offset_s IS NULL OR planned_arrival_offset_s >= 0),  -- derived unless typed in
    planned_departure_offset_s  integer CHECK (planned_departure_offset_s IS NULL OR planned_departure_offset_s >= 0),
    offsets_entered             boolean NOT NULL DEFAULT false,     -- true = typed in, never overwritten
    CONSTRAINT uq_route_stops_route_sequence UNIQUE (route_id, stop_sequence),
    CONSTRAINT chk_route_stops_offsets
        CHECK (planned_arrival_offset_s IS NULL OR planned_departure_offset_s IS NULL
               OR planned_departure_offset_s >= planned_arrival_offset_s)
);

-- The ordered road segments of each route (routes can share roads). Derived.
CREATE TABLE IF NOT EXISTS public.route_segments (
    route_id         integer NOT NULL REFERENCES public.routes(route_id) ON DELETE CASCADE,
    seq              integer NOT NULL CHECK (seq > 0),
    road_id          integer NOT NULL REFERENCES public.road_segments(road_id),
    reversed         boolean NOT NULL,
    start_measure_m  numeric(10,2) NOT NULL CHECK (start_measure_m >= 0),
    end_measure_m    numeric(10,2) NOT NULL,
    PRIMARY KEY (route_id, seq),
    CONSTRAINT chk_route_segments_measures CHECK (end_measure_m > start_measure_m)
);


-- =====================================================================
-- PART 2: REFERENCE and TEMPORAL-REFERENCE data, configuration
-- =====================================================================
CREATE TABLE IF NOT EXISTS public.drivers (
    driver_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(100) NOT NULL,
    license_info  varchar(100)
);

CREATE TABLE IF NOT EXISTS public.vehicles (
    vehicle_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_no  varchar(20) UNIQUE,
    vehicle_type     varchar(50) NOT NULL,
    capacity         integer NOT NULL CHECK (capacity > 0),
    -- Active: used by the timetable generator. Reserved: kept free for trips entered by hand
    -- (the demo bus). Not Active: cannot be given any trip.
    status           varchar(30) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active','Reserved','Not Active'))
);

-- Planned departures. Versioned by validity dates (a timetable is revised); two
-- versions of the same departure may not be valid on overlapping dates.
-- Planned times at later stops come from route_stops offsets.
CREATE TABLE IF NOT EXISTS public.timetable_departures (
    departure_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id        integer NOT NULL REFERENCES public.routes(route_id),
    departure_time  time NOT NULL,
    valid_from      date NOT NULL,
    valid_to        date,
    source_doc      text,
    CONSTRAINT chk_timetable_validity CHECK (valid_to IS NULL OR valid_to >= valid_from),
    CONSTRAINT excl_timetable_version_overlap
        EXCLUDE USING gist (route_id WITH =, departure_time WITH =, daterange(valid_from, valid_to, '[]') WITH &&)
);

-- A road closed during a time window. Riders see it as a service alert.
CREATE TABLE IF NOT EXISTS public.road_closures (
    closure_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    road_id       integer NOT NULL REFERENCES public.road_segments(road_id),
    valid_period  tsrange NOT NULL CHECK (NOT isempty(valid_period)),
    reason        text,
    CONSTRAINT excl_road_closure_overlap EXCLUDE USING gist (road_id WITH =, valid_period WITH &&)
);

CREATE TABLE IF NOT EXISTS public.service_params (
    param_key    varchar(50) PRIMARY KEY,
    param_value  numeric NOT NULL,
    unit         varchar(20),
    description  text NOT NULL
);

