-- =====================================================================
-- 03_derivation.sql
-- Functions and triggers that DERIVE data, so almost nothing is typed in.
-- Run after 01_schema.sql and 02_map_and_data.sql.
--
-- Run in : pgAdmin 4 > Query Tool on campus_shuttle.
-- Changes: creates functions, triggers and one view, then back-fills derived
--          data for the rows loaded by file 02.
-- Rerun  : safe (CREATE OR REPLACE / DROP TRIGGER IF EXISTS).
--
-- TRIGGERS RUN AUTOMATICALLY. This script only CREATES them, once. From then
-- on PostgreSQL fires each trigger every time its event happens (every insert,
-- update or delete on the table), whoever causes it: the simulator, pgAdmin,
-- an app. Functions that are NOT triggers (generate_service_day,
-- reprocess_trip, rebuild_all_derived) are called on purpose.
--
-- What is derived, and by what
--   stops: zone, road, snapped point ............ trigger on stops
--   route line, route_segments, distances,
--   planned offsets ............................. deferred trigger on route_stops
--   trip scheduled_end + planned stop events .... triggers on trips
--   trips for a date ............................ function generate_service_day()
--   fix -> trip, route position, road ........... trigger on vehicle_position
--   actual stop arrival / departure ............. same trigger (geofence rule)
--   trip actual_start / actual_end / status ..... trigger on trip_stop_event
--   segment traversals .......................... trigger when a trip completes
--   typical speed per road and time of day ...... view v_segment_speed
--
-- Stop-detection rule (tunable in service_params):
--   ARRIVAL   = the moment the shuttle's path enters the geofence (geofence_radius_m) of
--               the next unvisited stop, interpolated between the last fix outside and
--               the first fix inside.
--   DEPARTURE = the moment the path leaves the geofence, interpolated the same way.
--   DWELL     = a stay shorter than min_dwell_s is a drive-by and is discarded.
-- Nearness alone is never enough: it must also be the next stop the trip is expected to serve.
-- =====================================================================


